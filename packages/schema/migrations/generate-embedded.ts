/** Node-only build tooling; never imported by the native migration entry point. */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { DatabaseSync } from "node:sqlite";
import "./full.js";
import { getMigrations, assertMigrationSequence } from "./registry.js";
import {
  quoteSqlIdentifier,
  type SQLiteBaseline,
  type SQLiteBaselineIndex,
} from "./baseline.js";

export const EMBEDDED_OUTPUT = new URL(
  "./embedded-data.generated.ts",
  import.meta.url,
);

export async function generatedEmbeddedSource(): Promise<string> {
  const registered = getMigrations();
  assertMigrationSequence(registered);
  const entries = await Promise.all(
    registered.map(async (migration) => ({
      version: migration.version,
      name: migration.name,
      sql: (await readFile(migration.source, "utf8")).replace(/\r\n/g, "\n"),
    })),
  );
  if (!entries[0])
    throw new Error("Core migration is required to generate embedded SQL");
  const db = new DatabaseSync(":memory:");
  let baseline: SQLiteBaseline;
  try {
    db.exec(entries[0].sql);
    const tables = db
      .prepare(
        "SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name",
      )
      .all() as Array<{ name: string; sql: string }>;
    baseline = {
      version: 1,
      name: entries[0].name,
      tables: tables.map((table) => {
        const indexRows = db
          .prepare(`PRAGMA index_list(${quoteSqlIdentifier(table.name)})`)
          .all() as Array<{
          seq: number;
          name: string;
          unique: number;
          origin: string;
          partial: number;
        }>;
        const indexes: SQLiteBaselineIndex[] = indexRows
          .map(({ seq: _seq, ...metadata }) => ({
            name: metadata.name,
            metadata,
            sql: (
              db
                .prepare(
                  "SELECT sql FROM sqlite_master WHERE type='index' AND name=?",
                )
                .get(metadata.name) as { sql: string | null }
            ).sql,
            columns: db
              .prepare(
                `PRAGMA index_xinfo(${quoteSqlIdentifier(metadata.name)})`,
              )
              .all(),
          }))
          .sort((left, right) => left.name.localeCompare(right.name));
        return {
          name: table.name,
          sql: table.sql,
          columns: db
            .prepare(`PRAGMA table_xinfo(${quoteSqlIdentifier(table.name)})`)
            .all(),
          foreignKeys: db
            .prepare(
              `PRAGMA foreign_key_list(${quoteSqlIdentifier(table.name)})`,
            )
            .all(),
          indexes,
        };
      }),
    };
  } finally {
    db.close();
  }
  return `// Generated by migrations/generate-embedded.ts. Do not edit by hand.\n// Runtime imports below are type-only; SQL comes from the registered immutable files.\nimport type { SQLiteMigrationEntry } from "./apply";\nimport type { SQLiteBaseline } from "./baseline";\n\n// prettier-ignore\nexport const EMBEDDED_MIGRATIONS = ${JSON.stringify(entries, null, 2)} as const satisfies readonly SQLiteMigrationEntry[];\n\n// prettier-ignore\nexport const EMBEDDED_CORE_BASELINE = ${JSON.stringify(baseline, null, 2)} as const satisfies SQLiteBaseline;\n`;
}

export async function generateEmbedded(check = false): Promise<void> {
  const expected = await generatedEmbeddedSource();
  if (check) {
    const actual = await readFile(EMBEDDED_OUTPUT, "utf8");
    if (actual !== expected)
      throw new Error(
        "Embedded migrations are stale. Run pnpm --filter @locallab/schema generate:embedded.",
      );
  } else await writeFile(EMBEDDED_OUTPUT, expected, "utf8");
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  await generateEmbedded(process.argv.includes("--check"));
